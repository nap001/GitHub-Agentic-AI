import { supabase } from '../config/supabase.js';

/**
 * Retrieves all assigned active repositories configured for nightly reviews.
 */
export async function getActiveAssignedRepositories() {
  if (!supabase) return [];

  const { data, error } = await supabase
    .from('assigned_repositories')
    .select('*')
    .eq('is_active', true);

  if (error) {
    console.error('[Supabase Service] Failed to fetch assigned repositories:', error);
    throw error;
  }

  return data || [];
}

/**
 * Gets a map of file paths to their last reviewed metadata for a given repository.
 * Used to avoid redundant reviews if file content hasn't changed within review_interval_days.
 * 
 * @param {string} repositoryId 
 * @returns {Promise<Map<string, { lastBlobSha: string, lastReviewedAt: Date }>>}
 */
export async function getReviewedFilesMap(repositoryId) {
  const map = new Map();
  if (!supabase || !repositoryId) return map;

  const { data, error } = await supabase
    .from('reviewed_files')
    .select('file_path, last_blob_sha, last_reviewed_at')
    .eq('repository_id', repositoryId);

  if (error) {
    console.error(`[Supabase Service] Failed to fetch reviewed files for repo ${repositoryId}:`, error);
    return map;
  }

  for (const row of data || []) {
    map.set(row.file_path, {
      lastBlobSha: row.last_blob_sha,
      lastReviewedAt: new Date(row.last_reviewed_at),
    });
  }

  return map;
}

/**
 * Creates an entry in nightly_runs table to track the job.
 */
export async function createNightlyRunRecord({ repositoryId, repoFullName, branchName }) {
  if (!supabase) return { id: null };

  const { data, error } = await supabase
    .from('nightly_runs')
    .insert([
      {
        repository_id: repositoryId,
        repo_full_name: repoFullName,
        status: 'scanning',
        branch_name: branchName,
        started_at: new Date().toISOString(),
      },
    ])
    .select()
    .single();

  if (error) {
    console.error('[Supabase Service] Failed to create nightly_run record:', error);
    return { id: null };
  }

  return data;
}

/**
 * Updates a nightly_runs record with new status, metrics, or PR details.
 */
export async function updateNightlyRunRecord(runId, updates) {
  if (!supabase || !runId) return;

  const payload = { ...updates };
  if (['completed', 'failed'].includes(payload.status) && !payload.completed_at) {
    payload.completed_at = new Date().toISOString();
  }

  const { error } = await supabase
    .from('nightly_runs')
    .update(payload)
    .eq('id', runId);

  if (error) {
    console.error(`[Supabase Service] Failed to update nightly_run ${runId}:`, error);
  }
}

/**
 * Upserts reviewed file state so subsequent runs know the blob SHA and timestamp.
 */
export async function upsertReviewedFile({
  repositoryId,
  filePath,
  blobSha,
  hasOptimizations = false,
  nightlyRunId = null,
}) {
  if (!supabase || !repositoryId) return;

  const { error } = await supabase
    .from('reviewed_files')
    .upsert(
      {
        repository_id: repositoryId,
        file_path: filePath,
        last_blob_sha: blobSha,
        last_reviewed_at: new Date().toISOString(),
        has_optimizations: hasOptimizations,
        nightly_run_id: nightlyRunId,
      },
      { onConflict: 'repository_id,file_path' }
    );

  if (error) {
    console.error(`[Supabase Service] Failed to upsert reviewed file ${filePath}:`, error);
  }
}

/**
 * Records individual optimization proposals generated by the AI.
 */
export async function saveOptimizationProposals(proposals) {
  if (!supabase || !proposals || proposals.length === 0) return;

  const rows = proposals.map((p) => ({
    nightly_run_id: p.nightlyRunId,
    file_path: p.filePath,
    category: p.category,
    description: p.description,
    original_code: p.originalCode,
    optimized_code: p.optimizedCode,
    requires_human_verification: p.requiresHumanVerification ?? true,
  }));

  const { error } = await supabase.from('optimization_proposals').insert(rows);

  if (error) {
    console.error('[Supabase Service] Failed to save optimization proposals:', error);
  }
}
