import { Annotation } from '@langchain/langgraph';

/**
 * LangGraph state schema for the Nightly AI Code Review & Optimization workflow.
 */
export const NightlyReviewAnnotation = Annotation.Root({
  // Raw files scanned from repo: [{ path, sha, content, detectedTargets, priorityScore }]
  files: Annotation({
    reducer: (_, next) => next,
    default: () => [],
  }),

  // Target optimizations or flags (e.g. ['simd', 'openmp', 'cache', 'algorithmic'])
  targetOptimizations: Annotation({
    reducer: (_, next) => next,
    default: () => ['simd', 'openmp', 'cache', 'algorithmic'],
  }),

  // All extracted granular optimization proposals across processed files
  optimizations: Annotation({
    reducer: (prev, next) => (next ? prev.concat(next) : prev),
    default: () => [],
  }),

  // Files where modifications are synthesized and ready for git commit:
  // [{ path, originalContent, modifiedContent, appliedProposals: [] }]
  modifiedFiles: Annotation({
    reducer: (_, next) => next,
    default: () => [],
  }),

  // Executive summary markdown generated by the pipeline for the Pull Request body
  reviewSummary: Annotation({
    reducer: (_, next) => next,
    default: () => '',
  }),

  // Errors logged during file analysis or synthesis
  errors: Annotation({
    reducer: (prev, next) => (next ? prev.concat(next) : prev),
    default: () => [],
  }),
});
